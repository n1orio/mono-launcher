// Генерирует lib/i18n-keys.ts — union-тип всех ключей из базового locales/ru.json.
// Запуск: node scripts/gen-i18n-keys.mjs (также в postinstall).
// Даёт автокомплит в t("...") и отлов опечаток через (string & {}) сигнатуру.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const ru = JSON.parse(fs.readFileSync(path.join(root, "locales", "ru.json"), "utf8"));
const keys = Object.keys(ru).filter((k) => k !== "__meta__").sort();

const out = `// AUTO-GENERATED by scripts/gen-i18n-keys.mjs — do not edit.
// Base: locales/ru.json (${keys.length} keys).
export type I18nKey =
${keys.map((k) => `  | ${JSON.stringify(k)}`).join("\n")};
`;

fs.writeFileSync(path.join(root, "lib", "i18n-keys.ts"), out);
console.log(`i18n-keys.ts: ${keys.length} keys`);
